// New Zealand public-sector agencies — the NZ counterpart of canberraGov.ts /
// adelaideGov.ts, harvested from the government jobs board (jobs.govt.nz) and
// archived daily in D1 under source 'nz-gov' (scripts/nzgov-to-d1.py).
//
// SCOPE: only agencies advertising in Auckland or Wellington are listed. The
// board covers the whole country, but those are the two NZ cities the app plots,
// and an agency with no pin has nowhere to live. Agencies elsewhere still get
// scraped and archived — they simply are not roster cards yet.
//
// ids are `nz-<slug>`, generated by exactly the same rule as agency_id() in the
// scraper (lowercase, non-alphanumerics collapsed to '-', trimmed, prefixed,
// truncated to 60). They MUST stay byte-identical to the ids written into D1 or
// a card resolves no vacancies. That rule is why a couple read oddly:
// "NZ Police" becomes `nz-nz-police`, and macrons are dropped rather than
// transliterated, so Waitematā becomes `…-waitemat`. Both are kept as-is —
// matching the archive matters more than a tidy slug.
//
// The hub is where each agency actually advertises most, taken from the harvest
// rather than assumed: NZ's public service is Wellington-centred, but the health
// districts and a few others are Auckland employers.
//
// To refresh this list when the board's employer set changes, run
//   python scripts/nzgov-to-d1.py --agencies
// which prints {id, name, city, roles} for everything it saw, and reconcile the
// table below against it. It is a deliberate manual step: a new agency needs a
// sector and a hub decided, not just an id.
//
// The four Te Whatu Ora districts and the Northern Regional Alliance are health
// employers, not central-government ones, so they carry the Healthcare sector
// and group — the Healthcare filter should find a hospital district, and the
// Government filter should not be the only way to reach it.
