// Agencies that are health employers rather than central government.
const HEALTH_RE = /Te Whatu Ora|Northern Regional Alliance/;

const STOP = new Set(["of", "and", "the", "for", "&", "a"]);

function h01(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return ((h >>> 0) % 100000) / 100000;
}

// Must match agency_id() in scripts/nzgov-to-d1.py exactly — see the note above.
export function nzAgencyId(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return ("nz-" + slug).slice(0, 60);
}

function govAcronym(name: string): string {
  const words = name.split(/[\s,]+/).filter((w) => w && !STOP.has(w.toLowerCase()));
  if (words.length >= 2) {
    return words
      .map((w) => w[0].toUpperCase())
      .join("")
      .slice(0, 6);
  }
  return (words[0] || name).slice(0, 5).toUpperCase();
}

const GOV_SKILLS = [
  "Policy & Governance",
  "Public Administration",
  "Project Delivery",
  "Data & Analytics",
  "Community Services",
];
const HEALTH_SKILLS = [
  "Nursing",
  "Allied Health",
  "Medical Practice",
  "Health Administration",
  "Community Services",
];
const GOV_ROLES = ["Corporate & Policy", "Frontline Services", "Operations"];
const HEALTH_ROLES = ["Clinical", "Nursing & Midwifery", "Corporate & Support"];

function buildAgency([name, , seenRoles]: AgencyEntry): Company {
  const health = HEALTH_RE.test(name);
  const h = h01(name);
  const h2 = h01(name + "::b");
  // NZD bands, lower than the APS equivalents.
  const salaryNum = Math.round((92 + (h - 0.5) * 40) * 1000); // ~72k .. 112k
  const salaryK = Math.round(salaryNum / 1000);
  const turnover = +(7 + h2 * 8).toFixed(1);
  // openRoles seeds from what the first harvest actually saw, not a hash — a
  // card that is opened replaces it with the live count from D1 (see
  // lib/openRolesFn.ts), so this is only what shows before that resolves.
  const split = [0.45, 0.33, 0.22];
  const roleTitles = health ? HEALTH_ROLES : GOV_ROLES;
  const roles: RoleBreakdown[] = roleTitles.map((title, i) => ({
    title,
    count: Math.max(1, Math.round(seenRoles * split[i])),
  }));
  const delta = Math.round((h - 0.5) * 16);
  const acr = govAcronym(name);
  return {
    id: nzAgencyId(name),
    ticker: acr,
    name,
    pill: acr,
    domain: deriveDomain(name),
    sector: health ? "Healthcare" : "Government",
    group: health ? "Healthcare and Life Sciences" : "Infrastructure and Government",
    private: true,
    headcount: 0,
    growth: 0,
    openRoles: seenRoles,
    salary: `$${salaryNum.toLocaleString("en-US")}`,
    salaryShort: `$${salaryK}K`,
    salaryNum,
    turnover,
    salaryDelta: `${delta >= 0 ? "+" : "−"}${Math.abs(delta)}%`,
    metroDelta: `${delta >= 0 ? "+" : "−"}${Math.abs(delta)}% vs metro`,
    trend: [],
    revPerEmp: 0,
    ebitdaPerEmp: 0,
    timeToFill: `${Math.round(30 + h * 26)} days`,
    competition: h > 0.66 ? "High" : h > 0.33 ? "Medium" : "Low",
    skills: health ? HEALTH_SKILLS : GOV_SKILLS,
    roles,
  };
}

export const NZ_GOV_COMPANIES: Company[] = AGENCIES.map(buildAgency);
export const NZ_GOV_IDS: string[] = NZ_GOV_COMPANIES.map((c) => c.id);
export const NZ_GOV_NAMES: string[] = AGENCIES.map(([name]) => name);

// id → hub (Auckland or Wellington) so the map pins each agency in the city it
// actually advertises in. Used by mapboxGeo.ts.
export const NZ_GOV_HUB: Record<string, string> = Object.fromEntries(
  AGENCIES.map(([name, hub]) => [nzAgencyId(name), hub]),
);
